"""Real subprocess execution under a fenced lease with verifiable CAS output."""
from __future__ import annotations
import hashlib
from pathlib import Path
import sys
import tempfile
import time
import unittest
from atlas.phaseshift import compile_workflow
from atlas.phaselease import LeaseStore
from atlas.artifacts import ArtifactStore
from atlas.execution import SupervisedExecutor, ExecutionError

CAT={'m':{'bytes':100,'format':'gguf','role':'llm','lineage_verified':True}}
NODES=[{'id':'phone','trust':'local','capabilities':['llama'],'models':['m'],
        'ram_available_mb':1000,'ram_headroom_mb':100,'disk_free_bytes':200000,
        'thermal_c':31,'priority':0}]
JOBS=[{'id':'job','engine':'llama','models':['m'],'ram_mb':100,'duration_slots':1,
       'output_bytes':2048,'privacy':'local_only'}]

class ExecutionTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory()
        self.base=Path(self.tmp.name)
        self.cas=ArtifactStore(self.base/'cas')
        self.plan=compile_workflow(JOBS,NODES,CAT,horizon=3)
        self.store=LeaseStore(self.base/'jobs.sqlite',self.plan,JOBS,NODES,CAT,artifacts=self.cas)
        self.root=self.base/'work'
        self.executor=SupervisedExecutor(self.store,self.cas,self.root)

    def tearDown(self):
        self.store.close()
        self.tmp.cleanup()

    def run_command(self, code, *, ttl=4, timeout=10, suffix='.bin', max_log_bytes=4096):
        return self.executor.run('job','phone',
            [sys.executable,'-c',code,'{output}'],ttl=ttl,
            timeout_seconds=timeout,suffix=suffix,max_log_bytes=max_log_bytes)

    def test_success_publishes_real_content_in_cas(self):
        text=b'generated bytes'
        result=self.run_command("from pathlib import Path;import sys;Path(sys.argv[1]).write_bytes(b'generated bytes')")
        self.assertEqual(result['status'],'COMPLETED')
        self.assertEqual(result['sha256'],hashlib.sha256(text).hexdigest())
        self.assertTrue(self.cas.verify(result['sha256']))
        self.assertEqual(self.store.status('job')['state'],'COMPLETED')
        self.assertFalse(Path(result['output_path']).exists())  # temporary output removed after durable CAS
        self.assertTrue(Path(result['log_path']).is_file())

    def test_failed_process_releases_lease_and_allows_retry(self):
        with self.assertRaisesRegex(ExecutionError,'PROCESS_FAILED'):
            self.run_command('import sys;sys.exit(17)')
        self.assertEqual(self.store.status('job')['state'],'FAILED')
        self.assertEqual(self.store.status('job')['last_error'],'PROCESS_FAILED')
        result=self.run_command("from pathlib import Path;import sys;Path(sys.argv[1]).write_bytes(b'ok')")
        self.assertEqual(result['epoch'],2)

    def test_timeout_terminates_process_and_releases_lease(self):
        with self.assertRaisesRegex(ExecutionError,'PROCESS_TIMEOUT'):
            self.run_command('import time;time.sleep(30)',ttl=2,timeout=0.3)
        self.assertEqual(self.store.status('job')['state'],'FAILED')
        self.assertEqual(self.store.status('job')['last_error'],'PROCESS_TIMEOUT')

    def test_missing_output_fails_closed(self):
        with self.assertRaisesRegex(ExecutionError,'OUTPUT_MISSING'):
            self.run_command('print("hello")')
        self.assertEqual(self.store.status('job')['state'],'FAILED')

    def test_heartbeat_prevents_expiry_during_long_running_command(self):
        result=self.run_command("import time,sys;from pathlib import Path;time.sleep(1.5);Path(sys.argv[1]).write_bytes(b'ok')",ttl=1,timeout=5)
        self.assertEqual(result['status'],'COMPLETED')

    def test_stdout_is_bounded_and_treated_as_private(self):
        result=self.run_command("from pathlib import Path;import sys;print('X'*200000);Path(sys.argv[1]).write_bytes(b'ok')",max_log_bytes=128)
        log=Path(result['log_path'])
        self.assertLessEqual(log.stat().st_size,128)
        self.assertEqual(log.stat().st_mode & 0o077,0)
        self.assertEqual(self.root.stat().st_mode & 0o077,0)

    def test_invalid_command_is_rejected_before_claim(self):
        for argv in ([],['/bin/echo','hello'],['/bin/echo','{output}','{output}'],['/bin/sh','-c','echo x\0']):
            with self.subTest(argv=argv):
                with self.assertRaises(ExecutionError):
                    self.executor.run('job','phone',argv)
        self.assertEqual(self.store.status('job')['state'],'PENDING')

    def test_nonzero_command_does_not_publish_partial_output(self):
        code="from pathlib import Path;import sys;Path(sys.argv[1]).write_bytes(b'partial');sys.exit(2)"
        with self.assertRaises(ExecutionError): self.run_command(code)
        self.assertFalse(any((self.base/'cas'/'objects').iterdir()))

if __name__=='__main__': unittest.main()
